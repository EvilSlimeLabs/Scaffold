def level_dat(path, name, spawn, game_type=6, simulation=4):
    """A void superflat, spectator by default, with nothing that changes a
    block switched on: no fire spreading, no random ticks, no mobs, no weather,
    no drops, and the time held at noon."""
    import time
    root = Compound(dict(LEVEL))
    root.update({
        "LevelName": String(name),
        "SpawnX": Int(spawn[0]), "SpawnY": Int(spawn[1]), "SpawnZ": Int(spawn[2]),
        "RandomSeed": Long(0), "LastPlayed": Long(int(time.time())),
        "currentTick": Long(0), "Time": Long(6000),
        "GameType": Int(game_type), "Difficulty": Int(0),
        "serverChunkTickRange": Int(simulation),
        "spawnMobs": Byte(0), "showcoordinates": Byte(1),
        "dodaylightcycle": Byte(0), "doweathercycle": Byte(0),
        "dofiretick": Byte(0), "randomtickspeed": Int(0),
        "domobspawning": Byte(0), "mobgriefing": Byte(0),
        "tntexplodes": Byte(0), "doinsomnia": Byte(0),
        "doentitydrops": Byte(0), "dotiledrops": Byte(0),
        "commandblockoutput": Byte(0), "sendcommandfeedback": Byte(0),
    })
    payload = _nbt(root)
    with open(path, "wb") as f:
        f.write(struct.pack("<ii", 10, len(payload)))
        f.write(payload)
