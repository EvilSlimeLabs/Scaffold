"""Write a Bedrock world directly: chunks, block entities, entities and level.dat.

Nothing here is shipped. `tools/checks/gallery.py` is what uses it.

A Bedrock world is a LevelDB database in `db/` beside a `level.dat`. Rather than
writing LevelDB's sorted tables, everything is written to the database's log,
which LevelDB replays into a table the first time the world is opened: a
`MANIFEST` naming the log, a `CURRENT` naming the manifest, and the log itself,
one write batch of every key. That is the format LevelDB writes a change in
before it ever builds a table, so the game reads it the way it reads its own.

What the keys hold is Bedrock's chunk format, at chunk version 42:

- a chunk's version, and its finalised state, so the game neither generates nor
  populates it
- `Data3D`: a height map and the chunk's biomes, every section plains
- one `SubChunkPrefix` per sixteen blocks of height that holds anything: block
  storages in the version 9 layout, the second storage for water
- `BlockEntity`: the block entities in the chunk, one NBT compound after another
- `digp` and `actorprefix`: which entities a chunk holds, and each entity

A chunk the world does not hold is generated by the world's own generator,
which for the gallery is a void.
"""
import io
import math
import os
import struct

import nbtlib
from nbtlib import Byte, Compound, Float, Int, List, Long, String

## the overworld's lowest block and its sixteen-high sections
MIN_Y = -64
SECTIONS = 24
CHUNK_VERSION = 42
PLAINS = 1

TAG_DATA3D = 43
TAG_VERSION = 44
TAG_SUBCHUNK = 47
TAG_BLOCK_ENTITY = 49
TAG_FINALIZED = 54

## how many chunks either side of the origin are written empty, which is wider
## than the platform the void generator puts there
VOID_PLATFORM = 3


# --- LevelDB's log ------------------------------------------------------------

def _crc32c_table():
    table = []
    for n in range(256):
        c = n
        for _ in range(8):
            c = (c >> 1) ^ 0x82F63B78 if c & 1 else c >> 1
        table.append(c)
    return table


_CRC = _crc32c_table()


def crc32c(data, crc=0):
    crc ^= 0xFFFFFFFF
    for b in data:
        crc = _CRC[(crc ^ b) & 0xFF] ^ (crc >> 8)
    return crc ^ 0xFFFFFFFF


def _masked(crc):
    return ((((crc >> 15) | (crc << 17)) & 0xFFFFFFFF) + 0xA282EAD8) & 0xFFFFFFFF


def _varint(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


BLOCK = 32768
FULL, FIRST, MIDDLE, LAST = 1, 2, 3, 4


def log_records(payloads):
    """LevelDB's log format: records cut to fit 32 KiB blocks, each checked."""
    out = bytearray()
    for payload in payloads:
        left = payload
        first = True
        while True:
            room = BLOCK - len(out) % BLOCK
            if room < 7:
                out += b"\0" * room
                room = BLOCK
            take = left[:room - 7]
            left = left[len(take):]
            kind = (FULL if first and not left else FIRST if first
                    else LAST if not left else MIDDLE)
            crc = _masked(crc32c(bytes([kind]) + take))
            out += struct.pack("<IHB", crc, len(take), kind) + take
            first = False
            if not left:
                break
    return bytes(out)


def write_db(folder, items, per_batch=None):
    """A LevelDB database holding `items`, a mapping of key to value.

    `per_batch` cuts the writes into batches of that many keys, the way the
    game writes a chunk at a time, rather than one batch of everything.
    """
    os.makedirs(folder, exist_ok=True)
    pairs = list(items.items())
    size = per_batch or len(pairs) or 1
    batches, sequence = [], 1
    for start in range(0, len(pairs), size):
        chunk = pairs[start:start + size]
        batch = bytearray(struct.pack("<QI", sequence, len(chunk)))
        for key, value in chunk:
            batch += b"\x01" + _varint(len(key)) + key + _varint(len(value)) + value
        batches.append(bytes(batch))
        sequence += len(chunk)
    with open(os.path.join(folder, "000003.log"), "wb") as f:
        f.write(log_records(batches))
    comparator = b"leveldb.BytewiseComparator"
    edit = (_varint(1) + _varint(len(comparator)) + comparator
            + _varint(2) + _varint(3)          # the log to replay
            + _varint(9) + _varint(0)          # no previous log
            + _varint(3) + _varint(4)          # the next file number
            + _varint(4) + _varint(0))         # the last sequence written
    with open(os.path.join(folder, "MANIFEST-000002"), "wb") as f:
        f.write(log_records([edit]))
    with open(os.path.join(folder, "CURRENT"), "w", newline="\n") as f:
        f.write("MANIFEST-000002\n")


# --- chunks -------------------------------------------------------------------

def _nbt(compound):
    body = io.BytesIO()
    nbtlib.File(compound).write(body, byteorder="little")
    return body.getvalue()


def _storage(indices, palette):
    """One block storage: packed indices, then its palette as NBT."""
    bits = next(b for b in (1, 2, 3, 4, 5, 6, 8, 16) if (1 << b) >= len(palette))
    per = 32 // bits
    words = [0] * (-(-4096 // per))
    for i, value in enumerate(indices):
        words[i // per] |= value << ((i % per) * bits)
    out = bytearray([bits << 1])
    out += struct.pack("<%dI" % len(words), *words)
    out += struct.pack("<i", len(palette))
    for entry in palette:
        out += _nbt(entry)
    return bytes(out)


def _chunk_key(cx, cz, tag, extra=None):
    key = struct.pack("<iiB", cx, cz, tag)
    if extra is not None:
        key += struct.pack("<b", extra)
    return key


AIR = Compound({"name": String("minecraft:air"), "states": Compound({}),
                "version": Int(0)})


class World:
    """Blocks, water, block entities and entities by world position.

    An entity is its identifier, its position, its yaw and any fields of its
    own, such as a name or a painting's motive.
    """

    def __init__(self, version):
        self.version = version
        self.blocks = {}
        self.water = set()
        self.block_entities = {}
        self.entities = []

    def block(self, name, states):
        return Compound({"name": String(name),
                         "states": Compound(states),
                         "version": Int(self.version)})

    def items(self):
        """Every LevelDB key the world needs, and its value."""
        chunks = {}
        for (x, y, z) in list(self.blocks) + list(self.water):
            chunks.setdefault((x >> 4, z >> 4), set()).add((y - MIN_Y) >> 4)
        ## The void generator lays a stone platform round the origin in any
        ## chunk it is asked to make, so the chunks there are written empty and
        ## finished, and it is never asked.
        for cx in range(-VOID_PLATFORM, VOID_PLATFORM):
            for cz in range(-VOID_PLATFORM, VOID_PLATFORM):
                chunks.setdefault((cx, cz), set())
        items = {}
        water = self.block("minecraft:water", {"liquid_depth": Int(0)})
        for (cx, cz), sections in chunks.items():
            items[_chunk_key(cx, cz, TAG_VERSION)] = bytes([CHUNK_VERSION])
            items[_chunk_key(cx, cz, TAG_FINALIZED)] = struct.pack("<i", 2)
            items[_chunk_key(cx, cz, TAG_DATA3D)] = (
                struct.pack("<256h", *([0] * 256))
                + bytes([1]) + struct.pack("<i", PLAINS)
                + bytes([0xFF]) * (SECTIONS - 1))
            for section in sorted(sections):
                index = section + MIN_Y // 16
                base_y = section * 16 + MIN_Y
                palette, seen = [AIR], {}
                wet_palette = [AIR, water]
                cells = [0] * 4096
                wet = [0] * 4096
                any_wet = False
                for lx in range(16):
                    for lz in range(16):
                        for ly in range(16):
                            at = (cx * 16 + lx, base_y + ly, cz * 16 + lz)
                            i = (lx << 8) | (lz << 4) | ly
                            found = self.blocks.get(at)
                            if found is not None:
                                key = repr(found)
                                if key not in seen:
                                    seen[key] = len(palette)
                                    palette.append(found)
                                cells[i] = seen[key]
                            if at in self.water:
                                wet[i] = 1
                                any_wet = True
                layers = [_storage(cells, palette)]
                if any_wet:
                    layers.append(_storage(wet, wet_palette))
                items[_chunk_key(cx, cz, TAG_SUBCHUNK, index)] = (
                    bytes([9, len(layers)]) + struct.pack("<b", index)
                    + b"".join(layers))
        by_chunk = {}
        for (x, y, z), fields in self.block_entities.items():
            data = Compound(fields)
            data.update({"x": Int(x), "y": Int(y), "z": Int(z),
                         "isMovable": Byte(1)})
            by_chunk.setdefault((x >> 4, z >> 4), []).append(_nbt(data))
        for (cx, cz), parts in by_chunk.items():
            items[_chunk_key(cx, cz, TAG_BLOCK_ENTITY)] = b"".join(parts)
        held = {}
        for n, (identifier, pos, yaw, fields) in enumerate(self.entities):
            unique = 0x5CAFF0000 + n
            body = Compound({
                "identifier": String(identifier),
                "definitions": List[String]([String("+" + identifier)]),
                "UniqueID": Long(unique),
                "Pos": List[Float]([Float(v) for v in pos]),
                "Rotation": List[Float]([Float(yaw), Float(0)]),
                "Motion": List[Float]([Float(0), Float(0), Float(0)]),
                "OnGround": Byte(1),
                "Persistent": Byte(1),
            })
            body.update(fields)
            items[b"actorprefix" + struct.pack("<q", unique)] = _nbt(body)
            ## the chunk an entity stands in, rounding down west and north of
            ## the origin as well as east and south of it
            key = (math.floor(pos[0]) >> 4, math.floor(pos[2]) >> 4)
            held.setdefault(key, []).append(unique)
        for (cx, cz), ids in held.items():
            items[b"digp" + struct.pack("<ii", cx, cz)] = struct.pack(
                "<%dq" % len(ids), *ids)
        return items


